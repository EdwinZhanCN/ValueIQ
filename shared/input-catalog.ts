export type FieldId =
  InputId | SettingId | "project_name" | "decision_statement" | "other_notes";
export interface DefaultCandidate {
  value: number | string;
  source: string;
  tier: Tier;
  storage: "team_settings" | "catalog";
}
export interface FieldDefinition {
  id: FieldId;
  scope: "common" | Goal;
  question: string;
  info: string;
  respondent: string;
  role: "context" | "known" | "effect" | "cost";
  unit: string;
  period?: Period;
  type: "number" | "integer" | "text" | "enum" | "enum_array" | "number_array";
  requirement: "essential" | "recommended" | "optional" | "conditional";
  condition?: string;
  min?: number;
  exclusiveMin?: number;
  max?: number;
  maxLength?: number;
  options?: readonly string[];
  default?: DefaultCandidate;
}

